	  setButton: function(button, state, text, percent) {
	    if (!button || !button.isConnected) {
	      return;
	    }
	    const language = this.language || this.getLanguage();
	    button.dataset.state = state;
	    button.textContent = text;
	    button.classList.toggle("is-indeterminate", state === "downloading" && percent == null);
	    if (state === "downloading" && percent != null) {
	      button.style.backgroundSize = percent + "% 100%";
	    } else {
	      button.style.backgroundSize = "";
	    }
	    if (state === "downloading") {
	      button.title = language.cancelDownload;
	      button.disabled = false;
	    } else if (state === "success" || state === "error") {
	      button.title = language.reDownload;
	      button.disabled = false;
	    } else {
	      button.title = language.startDownload;
	      button.disabled = button.dataset.ready !== "1";
	    }
	  },
	  createButton: function(frame) {
	    const language = this.language;
	    const button = document.createElement("button");
	    button.type = "button";
	    button.className = "aio-gs-dl";
	    button.dataset.state = "idle";
	    button.dataset.ready = "0";
	    button.textContent = language.startDownload;
	    button.title = language.startDownload;
	    button.setAttribute("aria-live", "polite");
	    button.disabled = true;
	    button.addEventListener("click", (event) => {
	      event.preventDefault();
	      event.stopPropagation();
	      this.onButtonClick(button, frame);
	    });
	    return button;
	  },
	  onButtonClick: function(button, frame) {
	    const language = this.language;
	    if (button.dataset.state === "downloading") {
	      this.cancelCurrent();
	      this.setButton(button, "idle", language.startDownload, null);
	      return;
	    }
	    const url = this.readFrameUrl(frame);
	    if (!url) {
	      return;
	    }
	    this.cancelCurrent();
	    const requestId = this.requestId;
	    const dialog = button.closest("#gs-frame-dialog");
	    const titleNode = dialog && dialog.querySelector(".gs-frame-title");
	    const filename = this.generateFilename(url, titleNode ? titleNode.textContent : "");
	    this.download(
	      url,
	      filename,
	      () => {
	        if (requestId !== this.requestId) {
	          return;
	        }
	        this.setButton(button, "downloading", "0%", 0);
	      },
	      (percent, loaded, total) => {
	        if (requestId !== this.requestId) {
	          return;
	        }
	        if (percent == null) {
	          this.setButton(button, "downloading", language.downloadProgress + " " + CommonUtils.formatBytes(loaded), null);
	          return;
	        }
	        const progressText = percent + "% | " + CommonUtils.formatBytes(loaded) + "/" + CommonUtils.formatBytes(total);
	        this.setButton(button, "downloading", progressText, percent);
	      },
	      () => {
	        if (requestId !== this.requestId) {
	          return;
	        }
	        this.currentRequest = null;
	        const currentText = button.textContent || language.downloadCompleted;
	        const successText = currentText.startsWith("✓") ? currentText : "✓ " + currentText;
	        this.setButton(button, "success", successText, null);
	      },
	      (err) => {
	        if (requestId !== this.requestId) {
	          return;
	        }
	        this.currentRequest = null;
	        this.setButton(button, "error", language.downloadFailed, null);
	      }
	    );
	  },
	  cancelCurrent: function() {
	    this.requestId += 1;
	    if (!this.currentRequest) {
	      return;
	    }
	    const request = this.currentRequest;
	    this.currentRequest = null;
	    request.abort();
	  },
	  syncButton: function(dialog) {
	    const stage = dialog.querySelector(".gs-frame-stage");
	    const frame = stage && stage.querySelector("iframe");
	    if (!stage || !frame) {
	      return;
	    }
	    let button = stage.querySelector(".aio-gs-dl");
	    if (!button) {
	      button = this.createButton(frame);
	      stage.appendChild(button);
	    }
	    button.dataset.ready = this.readFrameUrl(frame) ? "1" : "0";
	    if (button.dataset.state === "idle") {
	      button.disabled = button.dataset.ready !== "1";
	    }
	  },
	  scanDialog: function() {
	    const dialog = document.getElementById("gs-frame-dialog");
	    if (!dialog) {
	      if (this.activeDialog) {
	        this.activeDialog = null;
	        this.cancelCurrent();
	      }
	      return;
	    }
	    if (this.activeDialog && this.activeDialog !== dialog) {
	      this.cancelCurrent();
	    }
	    this.activeDialog = dialog;
	    this.syncButton(dialog);
	  },
