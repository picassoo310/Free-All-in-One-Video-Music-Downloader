	  observe: function() {
	    if (this.observing || !document.documentElement) {
	      return;
	    }
	    this.observing = true;
	    const observer = new MutationObserver(() => {
	      this.scheduleScan();
	    });
	    observer.observe(document.documentElement, {
	      childList: true,
	      subtree: true,
	      attributes: true,
	      attributeFilter: ["src"]
	    });
	    this.scheduleScan();
	  },
